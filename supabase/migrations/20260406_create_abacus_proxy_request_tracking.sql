-- ============================================================================
-- Abacus Proxy Request Tracking Tables
-- Date: 2026-04-06
--
-- Purpose:
--   Track API requests/responses for analyzing intelligent routing effectiveness,
--   context condensation, and cost optimization.
--
-- Tables:
--   - public.abacus_proxy_requests (main request log)
--   - public.abacus_proxy_request_contexts (context condensation analysis)
--
-- Notes:
--   - Safe to run multiple times (idempotent)
--   - Based on model-proxy schema with routing intelligence enhancements
--   - Privacy-aware: payloads are optional (controlled by config)
-- ============================================================================

BEGIN;

-- Needed for gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------------------------------------------------------------------------
-- abacus_proxy_requests
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.abacus_proxy_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Stable request identifier used by the application
    request_id TEXT UNIQUE NOT NULL,

    -- Dimensions
    app_id VARCHAR(255),
    provider VARCHAR(100) NOT NULL DEFAULT 'routellm',
    model VARCHAR(255) NOT NULL,

    -- Timing / status
    request_timestamp TIMESTAMPTZ DEFAULT NOW(),
    response_timestamp TIMESTAMPTZ,
    latency_ms INTEGER,
    status_code INTEGER,
    error_message TEXT,

    -- Token counts
    request_token_count INTEGER,
    response_token_count INTEGER,

    -- Cost tracking
    estimated_cost NUMERIC(10,6),

    -- Intelligent routing metadata (NEW for abacus-proxy)
    routing_method VARCHAR(50),  -- 'intelligent', 'direct', 'fallback'
    requested_model VARCHAR(255), -- Model requested by client
    selected_model VARCHAR(255),  -- Actual model used (may differ from requested)
    value_index_score INTEGER,    -- Value-index score of selected model (0-100)
    use_case_detected VARCHAR(50), -- 'coding', 'architecting', 'condensation'

    -- Payloads (privacy sensitive - optional storage)
    request_payload JSONB,
    response_payload JSONB,

    -- Character count for analysis
    prompt_char_count INTEGER,

    -- Optional: lightweight metadata for analysis/debugging
    metadata JSONB DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ DEFAULT NOW()
);

COMMENT ON TABLE public.abacus_proxy_requests IS
    'Request tracking for abacus-proxy. Tracks intelligent routing decisions, cost, and performance.';

COMMENT ON COLUMN public.abacus_proxy_requests.request_id IS
    'Opaque request id generated by abacus-proxy (used for correlation).';
COMMENT ON COLUMN public.abacus_proxy_requests.routing_method IS
    'How the model was selected: intelligent (value-index), direct (client specified), fallback (error recovery).';
COMMENT ON COLUMN public.abacus_proxy_requests.value_index_score IS
    'Value-index score (0-100) of selected model. Higher = better capability/cost ratio.';
COMMENT ON COLUMN public.abacus_proxy_requests.use_case_detected IS
    'Detected use case for intelligent routing: coding, architecting, or condensation.';
COMMENT ON COLUMN public.abacus_proxy_requests.request_payload IS
    'Outbound payload sent to RouteLLM (privacy sensitive - optional storage).';
COMMENT ON COLUMN public.abacus_proxy_requests.response_payload IS
    'Final response payload from RouteLLM (privacy sensitive - optional storage).';

-- ---------------------------------------------------------------------------
-- abacus_proxy_request_contexts
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.abacus_proxy_request_contexts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Link to request
    request_id TEXT NOT NULL REFERENCES public.abacus_proxy_requests(request_id) ON DELETE CASCADE,

    -- Contexts (raw + condensed)
    raw_request_context TEXT,
    condensed_request_context TEXT,

    -- Condensation provenance
    condensation_method VARCHAR(100),  -- 'mem0', 'rules_memory', 'code_jit', etc.
    condensation_version VARCHAR(50),
    condensation_trigger VARCHAR(100), -- 'threshold', 'manual', 'auto'

    -- Character counts
    raw_context_chars INTEGER,
    condensed_context_chars INTEGER,

    -- Token counts
    raw_context_token_count INTEGER,
    condensed_context_token_count INTEGER,

    -- Computed savings
    tokens_saved INTEGER GENERATED ALWAYS AS (
        COALESCE(raw_context_token_count, 0) - COALESCE(condensed_context_token_count, 0)
    ) STORED,

    created_at TIMESTAMPTZ DEFAULT NOW()
);

COMMENT ON TABLE public.abacus_proxy_request_contexts IS
    'Stores raw vs condensed request context for condensation effectiveness analysis.';

COMMENT ON COLUMN public.abacus_proxy_request_contexts.raw_request_context IS
    'Canonical raw context before condensation (optional - privacy sensitive).';
COMMENT ON COLUMN public.abacus_proxy_request_contexts.condensed_request_context IS
    'Condensed context actually sent to provider (optional - privacy sensitive).';
COMMENT ON COLUMN public.abacus_proxy_request_contexts.tokens_saved IS
    'Computed column: tokens saved by condensation (raw - condensed).';

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_apr_time
    ON public.abacus_proxy_requests(request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_apr_app_time
    ON public.abacus_proxy_requests(app_id, request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_apr_model_time
    ON public.abacus_proxy_requests(model, request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_apr_routing_method
    ON public.abacus_proxy_requests(routing_method, request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_apr_use_case
    ON public.abacus_proxy_requests(use_case_detected, request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_apr_status_errors
    ON public.abacus_proxy_requests(status_code)
    WHERE status_code >= 400;

CREATE INDEX IF NOT EXISTS idx_apr_request_id
    ON public.abacus_proxy_requests(request_id);

CREATE INDEX IF NOT EXISTS idx_apr_cost
    ON public.abacus_proxy_requests(estimated_cost DESC NULLS LAST)
    WHERE estimated_cost IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_aprc_request_id
    ON public.abacus_proxy_request_contexts(request_id);

-- ---------------------------------------------------------------------------
-- RLS + policies (idempotent)
-- ---------------------------------------------------------------------------
ALTER TABLE public.abacus_proxy_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.abacus_proxy_request_contexts ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'abacus_proxy_requests'
          AND policyname = 'Allow authenticated read access'
    ) THEN
        CREATE POLICY "Allow authenticated read access"
            ON public.abacus_proxy_requests
            FOR SELECT TO authenticated
            USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'abacus_proxy_request_contexts'
          AND policyname = 'Allow authenticated read access'
    ) THEN
        CREATE POLICY "Allow authenticated read access"
            ON public.abacus_proxy_request_contexts
            FOR SELECT TO authenticated
            USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'abacus_proxy_requests'
          AND policyname = 'Allow service role full access'
    ) THEN
        CREATE POLICY "Allow service role full access"
            ON public.abacus_proxy_requests
            FOR ALL TO service_role
            USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'abacus_proxy_request_contexts'
          AND policyname = 'Allow service role full access'
    ) THEN
        CREATE POLICY "Allow service role full access"
            ON public.abacus_proxy_request_contexts
            FOR ALL TO service_role
            USING (true);
    END IF;
END $$;

COMMIT;

